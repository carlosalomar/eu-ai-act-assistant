"""Prompting and answer parsing for the LLM (served by vLLM, OpenAI-compatible API).

Two prompt styles:
  * RAG: the model sees numbered sources and must cite them as [1], [2]...
    and reply NO_ANSWER when the sources do not cover the question;
  * LLM only (baseline): no sources, the model must name the articles itself.

Configuration (environment variables):
  LLM_BASE_URL  default http://localhost:8000/v1 (vLLM's OpenAI server)
  LLM_MODEL     default Qwen/Qwen2.5-7B-Instruct-AWQ
  LLM_API_KEY   default "EMPTY" (vLLM does not check it)
"""

import os
import re
from dataclasses import dataclass, field

from rag.references import reference_units

NO_ANSWER = "NO_ANSWER"
DEFAULT_MODEL = "Qwen/Qwen2.5-7B-Instruct-AWQ"

LANGUAGE_NAMES = {"en": "English", "es": "Spanish", "de": "German"}

ABSTENTION_MESSAGES = {
    "en": "I don't know: the AI Act and the GDPR do not answer this question.",
    "es": "No lo sé: el Reglamento de IA y el RGPD no responden a esta pregunta.",
    "de": "Das weiß ich nicht: Die KI-Verordnung und die DSGVO beantworten diese Frage nicht.",
}

RAG_SYSTEM = """You are a legal assistant for the EU AI Act (Regulation (EU) 2024/1689, \
as amended by Regulation (EU) 2026/1744) and the GDPR (Regulation (EU) 2016/679).

Rules:
1. Answer ONLY with information from the numbered sources below the question.
2. After every sentence, cite the source(s) it comes from with their number in \
square brackets. Never cite a source that does not support the sentence.
   Example: "Providers must keep the logs generated by the system [2]. Deployers \
must inform the workers affected [1][3]."
3. Only if none of the sources is relevant to the question, reply with exactly \
{no_answer} and nothing else.
4. Be concise: at most 150 words. Answer in {language}."""

LLM_ONLY_SYSTEM = """You are a legal assistant for the EU AI Act (Regulation (EU) 2024/1689) \
and the GDPR (Regulation (EU) 2016/679).

Rules:
1. Answer from your own knowledge of these two regulations.
2. Name the exact provisions your answer is based on, written as \
"Article N AI Act", "Article N GDPR" or "Annex N AI Act".
3. If the two regulations do not answer the question, reply with exactly {no_answer} \
and nothing else.
4. Be concise: at most 150 words. Answer in {language}."""


@dataclass
class Answer:
    question: str
    lang: str
    mode: str
    text: str                       # raw model output
    abstained: bool
    cited_units: list[str]          # ["ai_act:art5", "ai_act:anxIII"]
    cited_refs: list[str]           # human-readable citations in the answer's language
    sources: list = field(default_factory=list)   # retrieved Hit objects (RAG modes)

    @property
    def display_text(self) -> str:
        return ABSTENTION_MESSAGES[self.lang] if self.abstained else strip_no_answer(self.text)


def format_sources(hits) -> str:
    blocks = []
    for i, hit in enumerate(hits, 1):
        chunk = hit.chunk
        title = f" — {chunk['title']}" if chunk["title"] else ""
        blocks.append(f"[{i}] {chunk['ref_local']}{title}\n{chunk['text']}")
    return "\n\n".join(blocks)


def rag_messages(question: str, hits, lang: str) -> list[dict]:
    system = RAG_SYSTEM.format(no_answer=NO_ANSWER, language=LANGUAGE_NAMES[lang])
    user = f"Question: {question}\n\nSources:\n\n{format_sources(hits)}"
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def llm_only_messages(question: str, lang: str) -> list[dict]:
    system = LLM_ONLY_SYSTEM.format(no_answer=NO_ANSWER, language=LANGUAGE_NAMES[lang])
    return [{"role": "system", "content": system}, {"role": "user", "content": question}]


def is_abstention(text: str) -> bool:
    """The answer is an abstention if it is empty or starts with NO_ANSWER.
    A stray NO_ANSWER after a real answer (small models do this) is not."""
    return not text.strip() or text.strip().strip("*\"'`").startswith(NO_ANSWER)


def strip_no_answer(text: str) -> str:
    return re.sub(rf"[-*\s]*{NO_ANSWER}[.\s]*", " ", text).strip()


def parse_rag_citations(text: str, hits) -> tuple[list[str], list[str]]:
    """Map [n] markers to the cited chunks' units and citations (in order, deduplicated)."""
    units, refs = [], []
    for number in re.findall(r"\[(\d+)\]", text):
        index = int(number) - 1
        if 0 <= index < len(hits):
            hit = hits[index]
            if hit.unit not in units:
                units.append(hit.unit)
            if hit.chunk["ref_local"] not in refs:
                refs.append(hit.chunk["ref_local"])
    return units, refs


def parse_rag_answer(text: str, hits) -> tuple[list[str], list[str]]:
    """[n] markers first; if the model wrote no markers, fall back to the
    articles it names in the text, kept only if they were among the sources."""
    units, refs = parse_rag_citations(text, hits)
    if units:
        return units, refs
    retrieved = {hit.unit: hit for hit in hits}
    for unit in parse_free_text_citations(text):
        if unit in retrieved:
            units.append(unit)
            refs.append(retrieved[unit].chunk["ref_local"].split("(")[0])
    return units, refs


def parse_free_text_citations(text: str) -> list[str]:
    """Citations written out by the model ("Article 5 AI Act") -> unit ids."""
    return list(dict.fromkeys(reference_units(text, fallback_law="ai_act")))


class LLMClient:
    def __init__(self, base_url: str | None = None, model: str | None = None,
                 temperature: float = 0.0, max_tokens: int = 400):
        from openai import OpenAI
        self.client = OpenAI(base_url=base_url or os.getenv("LLM_BASE_URL", "http://localhost:8000/v1"),
                             api_key=os.getenv("LLM_API_KEY", "EMPTY"))
        self.model = model or os.getenv("LLM_MODEL", DEFAULT_MODEL)
        self.temperature = temperature
        self.max_tokens = max_tokens

    def chat(self, messages: list[dict]) -> str:
        response = self.client.chat.completions.create(
            model=self.model, messages=messages,
            temperature=self.temperature, max_tokens=self.max_tokens)
        return (response.choices[0].message.content or "").strip()
